def run_experiment(method, seed):
    """Run single experiment for given method and seed"""
    fname = f"{method}_s{seed}_sp95.json"
    save_path = CFG.RESULTS_DIR / fname

    if save_path.exists():
        print(f"✓ Skipping {fname} (already exists)")
        return

    print(f"\n{'='*70}")
    print(f"Running: {method} | Seed: {seed}")
    print(f"{'='*70}")

    # Set seed
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    # Data
    train_loader, test_loader, train_dataset = get_cifar10_loaders(
        batch_size=CFG.BATCH, num_workers=2, seed=seed
    )

    # Model
    model = ResNetCIFAR().to(CFG.DEVICE)
    criterion = nn.CrossEntropyLoss()

    # Optimizer selection
    if method == 'sgd':
        optimizer = optim.SGD(
            model.parameters(), lr=CFG.LR, momentum=0.9,
            weight_decay=CFG.WD_SGD
        )
        scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, CFG.EPOCHS)
        is_sam = False

    elif method == 'sam_dense':
        base_opt = lambda params, **kwargs: optim.SGD(
            params, lr=CFG.LR, momentum=0.9, weight_decay=CFG.WD_SAM, **kwargs
        )
        optimizer = DenseSAM(model.parameters(), base_opt, rho=CFG.RHO)
        scheduler = optim.lr_scheduler.CosineAnnealingLR(
            optimizer.base_optimizer, CFG.EPOCHS
        )
        is_sam = True

    elif method == 'ssam_standard':
        base_opt = lambda params, **kwargs: optim.SGD(
            params, lr=CFG.LR, momentum=0.9, weight_decay=CFG.WD_SAM, **kwargs
        )
        optimizer = SparseSAM(
            model.parameters(), base_opt, rho=CFG.RHO,
            sparsity=CFG.SPARSITY, isonorm=False
        )
        scheduler = optim.lr_scheduler.CosineAnnealingLR(
            optimizer.base_optimizer, CFG.EPOCHS
        )
        is_sam = True

    elif method == 'ssam_isonorm':
        base_opt = lambda params, **kwargs: optim.SGD(
            params, lr=CFG.LR, momentum=0.9, weight_decay=CFG.WD_SAM, **kwargs
        )
        optimizer = SparseSAM(
            model.parameters(), base_opt, rho=CFG.RHO,
            sparsity=CFG.SPARSITY, isonorm=True
        )
        scheduler = optim.lr_scheduler.CosineAnnealingLR(
            optimizer.base_optimizer, CFG.EPOCHS
        )
        is_sam = True
    else:
        raise ValueError(f"Unknown method: {method}")

    # Training history
    history = {
        'train_loss': [], 'train_acc': [],
        'test_loss': [], 'test_acc': [],
        'perturb_norm': [], 'gen_gap': []
    }

    # Training loop
    for epoch in range(CFG.EPOCHS):
        start_time = time.time()

        # Train
        if is_sam:
            train_loss, train_acc, perturb_norm = train_epoch_sam(
                model, train_loader, optimizer, criterion, CFG.DEVICE
            )
        else:
            train_loss, train_acc = train_epoch_sgd(
                model, train_loader, optimizer, criterion, CFG.DEVICE
            )
            perturb_norm = 0.0

        # Evaluate
        test_loss, test_acc = evaluate(model, test_loader, CFG.DEVICE)

        # LR step
        scheduler.step()

        # Save metrics
        history['train_loss'].append(train_loss)
        history['train_acc'].append(train_acc)
        history['test_loss'].append(test_loss)
        history['test_acc'].append(test_acc)
        history['perturb_norm'].append(perturb_norm)
        history['gen_gap'].append(train_acc - test_acc)

        # Log
        if epoch % 10 == 0 or epoch == CFG.EPOCHS - 1:
            print(f"Epoch {epoch:3d} | Train: {train_acc:5.2f}% | "
                  f"Test: {test_acc:5.2f}% | Loss: {test_loss:.4f} | "
                  f"Norm: {perturb_norm:.4f} | Time: {time.time()-start_time:.1f}s")

    # Save results
    with open(save_path, 'w') as f:
        json.dump(history, f, indent=2)

    print(f"✓ Saved: {fname}")
    print(f"  Best Test Acc: {max(history['test_acc']):.2f}%")

