# SPARSE SAM (Magnitude-Based with Optional Iso-Norm)
# =========================================================================
class SparseSAM(optim.Optimizer):
    """
    Magnitude-Based Sparse SAM
    - Selects top-k gradients by magnitude (dynamic mask)
    - Optional Iso-Norm correction to preserve perturbation radius
    """
    def __init__(self, params, base_optimizer, rho=0.05, sparsity=0.95,
                 isonorm=True, **kwargs):
        defaults = dict(rho=rho, **kwargs)
        super().__init__(params, defaults)
        self.base_optimizer = base_optimizer(self.param_groups, **kwargs)
        self.param_groups = self.base_optimizer.param_groups
        self.sparsity = sparsity
        self.isonorm = isonorm

    def _grad_norm(self):
        """Compute L2 norm of all gradients"""
        return torch.norm(torch.stack([
            p.grad.norm(2) for g in self.param_groups
            for p in g['params'] if p.grad is not None
        ]), 2)

    @torch.no_grad()
    def first_step(self, zero_grad=False):
        # Step 1: Compute dense perturbation
        grad_norm = self._grad_norm()
        dense_scale = self.defaults['rho'] / (grad_norm + 1e-12)

        # Step 2: Apply sparse masking (top-k by magnitude)
        total_sq_norm = 0.0
        for group in self.param_groups:
            for p in group['params']:
                if p.grad is None: continue

                # Dense perturbation
                e_dense = p.grad * dense_scale

                # Top-k masking by magnitude
                k = max(1, int(e_dense.numel() * (1 - self.sparsity)))
                flat = e_dense.abs().view(-1)
                _, indices = torch.topk(flat, k)

                mask = torch.zeros_like(flat)
                mask[indices] = 1.0

                # Sparse perturbation
                e_sparse = e_dense * mask.view_as(p)
                self.state[p]['e_w'] = e_sparse
                total_sq_norm += e_sparse.pow(2).sum().item()

        # Step 3: Optional Iso-Norm rescaling
        if self.isonorm:
            masked_norm = math.sqrt(total_sq_norm)
            renorm = self.defaults['rho'] / (masked_norm + 1e-12)
        else:
            renorm = 1.0

        # Step 4: Apply perturbation
        for group in self.param_groups:
            for p in group['params']:
                if 'e_w' in self.state[p]:
                    self.state[p]['e_w'] *= renorm
                    p.add_(self.state[p]['e_w'])

        if zero_grad: self.zero_grad()

    @torch.no_grad()
    def second_step(self, zero_grad=False):
        # Revert perturbation
        for group in self.param_groups:
            for p in group['params']:
                if 'e_w' in self.state[p]:
                    p.sub_(self.state[p]['e_w'])

        # Apply gradient update
        self.base_optimizer.step()
        if zero_grad: self.zero_grad()

    def zero_grad(self):
        self.base_optimizer.zero_grad()

