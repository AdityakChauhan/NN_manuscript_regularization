def train_epoch_sgd(model, train_loader, optimizer, criterion, device):
    """Standard SGD training (no SAM)"""
    model.train()
    total_loss = 0.0
    correct = 0
    total = 0

    for x, y in train_loader:
        x, y = x.to(device), y.to(device)

        optimizer.zero_grad()
        out = model(x)
        loss = criterion(out, y)
        loss.backward()
        optimizer.step()

        total_loss += loss.item() * x.size(0)
        correct += (out.argmax(1) == y).sum().item()
        total += y.size(0)

    return total_loss / total, 100.0 * correct / total

def train_epoch_sam(model, train_loader, optimizer, criterion, device):
    """SAM training (Dense or Sparse)"""
    model.train()
    total_loss = 0.0
    correct = 0
    total = 0
    perturb_norms = []

    for batch_idx, (x, y) in enumerate(train_loader):
        x, y = x.to(device), y.to(device)

        # First forward-backward (compute perturbation)
        optimizer.zero_grad()
        out = model(x)
        loss = criterion(out, y)
        loss.backward()

        # Apply perturbation
        disable_bn_running_stats(model)
        optimizer.first_step(zero_grad=True)

        # Log perturbation norm (first batch only for efficiency)
        if batch_idx == 0:
            sq_sum = sum(
                optimizer.state[p]['e_w'].pow(2).sum().item()
                for g in optimizer.param_groups
                for p in g['params']
                if 'e_w' in optimizer.state[p]
            )
            perturb_norms.append(math.sqrt(sq_sum))

        # Second forward-backward (at perturbed position)
        criterion(model(x), y).backward()

        # Update weights and revert perturbation
        enable_bn_running_stats(model)
        optimizer.second_step(zero_grad=True)

        total_loss += loss.item() * x.size(0)
        correct += (out.argmax(1) == y).sum().item()
        total += y.size(0)

    avg_perturb_norm = perturb_norms[0] if perturb_norms else 0.0
    return total_loss / total, 100.0 * correct / total, avg_perturb_norm

@torch.no_grad()
def evaluate(model, test_loader, device):
    """Evaluation"""
    model.eval()
    criterion = nn.CrossEntropyLoss()
    total_loss = 0.0
    correct = 0
    total = 0

    for x, y in test_loader:
        x, y = x.to(device), y.to(device)
        out = model(x)
        loss = criterion(out, y)

        total_loss += loss.item() * x.size(0)
        correct += (out.argmax(1) == y).sum().item()
        total += y.size(0)

    return total_loss / total, 100.0 * correct / total

