def load_all():
    data = {}
    print(f"Loading results from: {RESULTS_DIR}")

    # Initialize dictionary structure
    for method in METHODS.keys():
        data[method] = {
            'test_acc': [], 'train_loss': [], 'test_loss': [],
            'perturb_norm': [], 'gen_gap': []
        }

        for seed in SEEDS:
            fpath = RESULTS_DIR / f"{method}_s{seed}_sp95.json"
            if not fpath.exists():
                print(f"⚠️  Missing: {fpath}")
                continue

            with open(fpath) as f:
                run = json.load(f)
                # Load all metrics safely
                for key in data[method].keys():
                    if key in run:
                        data[method][key].append(run[key])

    # Calculate Mean/Std Statistics
    stats_data = {}
    for method, runs in data.items():
        stats_data[method] = {}
        # Iterate over all 5 metrics
        for metric in ['test_acc', 'train_loss', 'test_loss', 'perturb_norm', 'gen_gap']:
            arr = np.array(runs[metric])
            if len(arr) == 0:
                continue

            # Align lengths if runs crashed/stopped early
            min_len = min(len(a) for a in arr)
            arr = np.array([a[:min_len] for a in arr])

            # Determine "best" (Max for Acc, Min for Loss/Gap)
            if 'acc' in metric:
                best_fn = np.max
            else:
                best_fn = np.min

            stats_data[method][metric] = {
                'mean': np.mean(arr, axis=0),
                'std': np.std(arr, axis=0),
                'best_mean': best_fn(np.mean(arr, axis=0)),
                'best_std': np.std([best_fn(run) for run in arr])
            }

    return data, stats_data

