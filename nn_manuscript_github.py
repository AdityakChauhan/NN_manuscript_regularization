import json
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path

# ==========================================
# CONFIGURATION
# ==========================================
RESULTS_DIR = Path('/content/')
SAVE_DIR = Path('/content/manuscript_figures')
SAVE_DIR.mkdir(parents=True, exist_ok=True)

METHODS = {
    'sgd':             {'label': 'SGD',                    'color': '#95A5A6', 'marker': 'o'},
    'sam_dense':       {'label': 'Dense SAM',              'color': '#3498DB', 'marker': 's'},
    'ssam_standard':   {'label': 'Standard Sparse SAM',    'color': '#E74C3C', 'marker': '^'},
    'ssam_isonorm':    {'label': 'Iso-Norm SSAM (Ours)',   'color': '#2ECC71', 'marker': 'D'}
}

SEEDS = [8, 42, 123]
RHO = 0.05
SPARSITY = 0.95
THEORETICAL_STANDARD_NORM = RHO * np.sqrt(1 - SPARSITY)

# ==========================================
# DATA LOADING
# ==========================================
def load_all():
    data = {}
    for method in METHODS.keys():
        data[method] = {'test_acc': [], 'test_loss': [], 'perturb_norm': [], 'gen_gap': []}
        for seed in SEEDS:
            fpath = RESULTS_DIR / f"{method}_s{seed}_sp95.json"
            if fpath.exists():
                with open(fpath) as f:
                    run = json.load(f)
                    for key in data[method].keys():
                        if key in run: data[method][key].append(run[key])

    stats_data = {}
    for method, runs in data.items():
        stats_data[method] = {}
        for metric in runs.keys():
            arr = np.array(runs[metric])
            if len(arr) == 0: continue
            min_len = min(len(a) for a in arr)
            arr = np.array([a[:min_len] for a in arr])
            stats_data[method][metric] = {
                'mean': np.mean(arr, axis=0),
                'std': np.std(arr, axis=0),
                'best_mean': np.max(np.mean(arr, axis=0)) if 'acc' in metric else np.min(np.mean(arr, axis=0)),
                'best_std': np.std([np.max(run) for run in arr]) if 'acc' in metric else np.std([np.min(run) for run in arr])
            }
    return stats_data

