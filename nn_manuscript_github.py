# INDIVIDUAL PLOTTING FUNCTIONS
# ==========================================
def save_plot(filename, title, ylabel, stats_data, metric_key, is_norm=False):
    plt.figure(figsize=(8, 6))
    if is_norm:
        plt.axhline(y=RHO, color='black', linestyle='--', linewidth=1.5, label=f'Target ρ={RHO}', zorder=1)
        plt.axhline(y=THEORETICAL_STANDARD_NORM, color='gray', linestyle=':', linewidth=2, label=f'Theory ≈{THEORETICAL_STANDARD_NORM:.4f}', zorder=1)

    for method, style in METHODS.items():
        if method not in stats_data or metric_key not in stats_data[method]: continue
        d = stats_data[method][metric_key]
        epochs = np.arange(len(d['mean']))

        if is_norm:
            # Clean logging for norms (ignore 0s)
            valid = [i for i, n in enumerate(d['mean']) if n > 1e-6]
            if not valid: continue

            # --- OVERLAP FIX FOR FIG 2 ---
            # Make Dense SAM a thick dashed line so it's visible behind the solid green line
            ls = '--' if method == 'sam_dense' else '-'
            lw = 4.0 if method == 'sam_dense' else 2.5
            zo = 2 if method == 'sam_dense' else 3 # Put Iso-norm on top

            plt.plot(np.array(valid), d['mean'][valid], label=style['label'], color=style['color'],
                     linewidth=lw, marker=style['marker'], markersize=6, markevery=10,
                     linestyle=ls, zorder=zo)
        else:
            plt.plot(epochs, d['mean'], label=style['label'], color=style['color'], linewidth=2)
            plt.fill_between(epochs, d['mean'] - d['std'], d['mean'] + d['std'], alpha=0.15, color=style['color'])

    plt.title(title, fontweight='bold', fontsize=14)
    plt.xlabel('Epoch', fontsize=12); plt.ylabel(ylabel, fontsize=12)
    plt.grid(True, alpha=0.3); plt.legend(fontsize=10)

    if is_norm:
        plt.ylim(0, 0.06) # Keep focus on the target area

    plt.tight_layout()
    plt.savefig(SAVE_DIR / filename, dpi=300)
    plt.close()
    print(f"✓ Saved: {filename}")

def save_bar_chart(stats_data):
    plt.figure(figsize=(9, 6))
    methods_list = [m for m in METHODS.keys() if m in stats_data]
    best_accs = [stats_data[m]['test_acc']['best_mean'] for m in methods_list]
    best_stds = [stats_data[m]['test_acc']['best_std'] for m in methods_list]
    labels = [METHODS[m]['label'].replace(' (Ours)', '') for m in methods_list]
    colors = [METHODS[m]['color'] for m in methods_list]

    x = np.arange(len(methods_list))
    bars = plt.bar(x, best_accs, yerr=best_stds, capsize=7, color=colors, alpha=0.8, edgecolor='black')
    for i, (acc, std) in enumerate(zip(best_accs, best_stds)):
        plt.text(i, acc + std + 0.1, f'{acc:.2f}%', ha='center', fontweight='bold')

    plt.xticks(x, labels, rotation=15); plt.ylabel('Best Test Accuracy (%)', fontsize=12)
    plt.title('Final Performance Comparison (95% Sparsity)', fontweight='bold', fontsize=14)
    plt.ylim(bottom=min(best_accs)-1); plt.grid(True, alpha=0.3, axis='y')
    plt.tight_layout()
    plt.savefig(SAVE_DIR / 'fig_final_bar_chart.png', dpi=300)
    plt.close()
    print(f"✓ Saved: fig_final_bar_chart.png")

