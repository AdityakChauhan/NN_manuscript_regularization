def plot_conceptual_figure_fixed():
    fig, ax = plt.subplots(figsize=(8, 8))

    # 1. Setup the "Weight Space"
    rho = 1.0
    ax.set_xlim(-1.3, 1.3)
    ax.set_ylim(-1.3, 1.3)
    ax.set_aspect('equal')

    # Remove axes ticks for clean look
    ax.axis('off')

    # 2. Draw the Neighborhood Ball (Radius rho)
    # Zorder 0 ensures it is behind everything
    circle = plt.Circle((0, 0), rho, color='#F8F9F9', ec='black', ls='--', lw=1.5, zorder=0)
    ax.add_artist(circle)
    ax.text(0.65, 0.9, r'$\rho$-Neighborhood', fontsize=12, color='#555555')

    # 3. Define Vectors
    # Dense Vector (Blue) - touches boundary
    angle_dense = np.deg2rad(55)
    dense_vec = np.array([np.cos(angle_dense), np.sin(angle_dense)]) * rho

    # Sparse Vector (Red) - collapsed inside
    angle_sparse = np.deg2rad(30)
    collapse_factor = 0.45
    sparse_vec = np.array([np.cos(angle_sparse), np.sin(angle_sparse)]) * (rho * collapse_factor)

    # Iso-Norm Vector (Green) - touches boundary, collinear with Sparse
    isonorm_vec = np.array([np.cos(angle_sparse), np.sin(angle_sparse)]) * rho

    # 4. Plot Vectors using annotate (Better head control)
    def draw_vector(vec, color, label_text, label_pos):
        # Draw the arrow
        ax.annotate('', xy=(vec[0], vec[1]), xytext=(0, 0),
                    arrowprops=dict(facecolor=color, edgecolor=color, width=3, headwidth=10, shrink=0.0),
                    zorder=5)
        # Draw the label with a white box background
        ax.text(label_pos[0], label_pos[1], label_text, color=color, fontsize=11, fontweight='bold',
                bbox=dict(facecolor='white', edgecolor='none', alpha=0.8, pad=1))

    # Draw Dense (Blue)
    draw_vector(dense_vec, '#3498DB', r'Dense SAM $(\epsilon_{dense})$',
                (dense_vec[0] + 0.05, dense_vec[1]))

    # Draw Iso-Norm (Green)
    draw_vector(isonorm_vec, '#2ECC71', r'Iso-Norm SSAM $(\epsilon_{iso})$',
                (isonorm_vec[0] + 0.05, isonorm_vec[1] - 0.05))

    # Draw Sparse (Red)
    draw_vector(sparse_vec, '#E74C3C', '', (0,0)) # No label at tip
    ax.text(sparse_vec[0] + 0.05, sparse_vec[1] - 0.15,
            r'Standard SSAM' + '\n' + r'(Collapsed)',
            fontsize=10, color='#E74C3C', ha='left', va='top')

    # 5. Add "Rescaling" Annotation
    # Curve arrow from Red tip to Green tip
    # We use a fancy arrow patch to connect them
    arrow = patches.FancyArrowPatch((sparse_vec[0], sparse_vec[1]),
                                    (isonorm_vec[0]*0.95, isonorm_vec[1]*0.95), # Stop slightly short of tip
                                    connectionstyle="arc3,rad=0",
                                    arrowstyle="->", color='black', lw=1.5, ls=':')
    ax.add_patch(arrow)

    # Label for the rescaling
    mid_x = (sparse_vec[0] + isonorm_vec[0]) / 2
    mid_y = (sparse_vec[1] + isonorm_vec[1]) / 2
    ax.text(mid_x + 0.05, mid_y - 0.1, r'Rescaling ($\gamma$)', fontsize=10, rotation=30)

    # Center Point
    ax.plot(0, 0, 'ko', markersize=6, zorder=10)
    ax.text(-0.15, -0.15, r'$w_t$', fontsize=14, fontweight='bold')

    plt.title('Geometric Visualization of Norm Correction', fontsize=14, fontweight='bold')
    plt.tight_layout()

    filename = SAVE_DIR / 'fig6_concept_fixed.png'
    plt.savefig(filename, dpi=300, bbox_inches='tight')
    print(f"✓ Saved fixed conceptual figure: {filename}")
    plt.show()

