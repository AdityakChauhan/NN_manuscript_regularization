def plot_all(stats_data):
    # Create 2x3 grid (2 Rows, 3 Columns)
    fig, axes = plt.subplots(2, 3, figsize=(20, 12))

    # Helper to plot mean +/- std
    def plot_metric(ax, metric_key, title, ylabel, log_scale=False):
        for method, style in METHODS.items():
            if method not in stats_data or metric_key not in stats_data[method]: continue

            d = stats_data[method][metric_key]
            epochs = np.arange(len(d['mean']))

            ax.plot(epochs, d['mean'], label=style['label'], color=style['color'], linewidth=2)
            ax.fill_between(epochs, d['mean'] - d['std'], d['mean'] + d['std'], alpha=0.15, color=style['color'])

        ax.set_xlabel('Epoch', fontsize=11)
        ax.set_ylabel(ylabel, fontsize=11)
        ax.set_title(title, fontweight='bold', fontsize=12)
        ax.grid(True, alpha=0.3, which='both')
        if log_scale: ax.set_yscale('log')
        if metric_key == 'test_acc': ax.legend(fontsize=9, loc='lower right')

    # --- Row 1: Performance Metrics ---
    plot_metric(axes[0, 0], 'test_acc', '(a) Test Accuracy (Higher is Better)', 'Accuracy (%)')
    # Train loss in Log scale to see convergence at 10^-3
    plot_metric(axes[0, 1], 'train_loss', '(b) Training Loss (Log Scale)', 'Loss', log_scale=True)
    # Test loss linear to see overfitting/stability
    plot_metric(axes[0, 2], 'test_loss', '(c) Test Loss (Lower is Better)', 'Loss')

    # --- Row 2: Analysis Metrics ---

    # (d) Perturbation Norms (The Mechanism)
