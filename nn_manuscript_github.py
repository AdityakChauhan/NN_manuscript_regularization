def get_cifar10_loaders(batch_size=128, num_workers=2, seed=42):
    """Get CIFAR-10 with 50% stratified subset"""
    mean = (0.4914, 0.4822, 0.4465)
    std = (0.2023, 0.1994, 0.2010)

    train_transform = T.Compose([
        T.RandomCrop(32, padding=4),
        T.RandomHorizontalFlip(),
        T.ToTensor(),
        T.Normalize(mean, std)
    ])

    test_transform = T.Compose([
        T.ToTensor(),
        T.Normalize(mean, std)
    ])

    # Full datasets
    train_full = torchvision.datasets.CIFAR10(
        './data', train=True, transform=train_transform, download=True
    )
    test_full = torchvision.datasets.CIFAR10(
        './data', train=False, transform=test_transform, download=True
    )

    # 50% stratified subset
    rng = np.random.RandomState(seed)
    targets = np.array(train_full.targets)
    indices = []
    for c in range(10):
        c_idx = np.where(targets == c)[0]
        rng.shuffle(c_idx)
        take = len(c_idx) // 2  # 50% per class
        indices.extend(c_idx[:take].tolist())

    train_subset = Subset(train_full, indices)

    train_loader = DataLoader(
        train_subset, batch_size=batch_size, shuffle=True,
        num_workers=num_workers, pin_memory=True, drop_last=True
    )
    test_loader = DataLoader(
        test_full, batch_size=batch_size, shuffle=False,
        num_workers=num_workers, pin_memory=True
    )

    return train_loader, test_loader, train_subset

